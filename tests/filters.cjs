const {test}=require('node:test');
const assert=require('node:assert/strict');
const {chromium,expect}=require('@playwright/test');
const {createServer}=require('../server.cjs');
test('Porcentajes exactos y rangos inclusivos funcionan en PC y consola con un único alcance',async()=>{
 const server=createServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||'chrome',headless:true});
 try{
  const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const percentages=[0,9,10,20,30,31,90];
  const catalogQueries=[];
  await page.route('**/api/**',async route=>{
   const u=new URL(route.request().url());let data={};
   if(u.pathname==='/api/stores')data=[];
   if(u.pathname==='/api/deals')catalogQueries.push(u.searchParams);
   if(u.pathname==='/api/deals')data=percentages.filter(n=>u.searchParams.get('onSale')!=='1'||n>0).map(n=>({gameID:String(n),title:'Descuento '+n,salePrice:100-n,normalPrice:100,savings:String(n),storeID:'1'}));
   if(u.pathname==='/api/console-catalog')data={platform:u.searchParams.get('platform'),region:'MX',checkedAt:Date.now(),sources:[],scope:'Prueba',next:null,items:percentages.filter(n=>u.searchParams.get('deals')!=='1'||n>0).map(n=>({id:String(n),title:'Descuento '+n,price:100-n,regular:100,discount:n,currency:'MXN',store:'Oficial',kind:'official',edition:'Xbox',url:'https://www.xbox.com'}))};
   await route.fulfill({contentType:'application/json',body:JSON.stringify(data)});
  });
  await page.goto('http://127.0.0.1:'+server.address().port);
  await expect(page.locator('#gamesGrid .steam-card')).toHaveCount(6);
  await expect(page.locator('#drawerPriceSlider,#consoleMaxPrice,#consoleOnlyDeals,#drawerOnSaleToggle')).toHaveCount(0);
  await page.locator('#toggleFineTuneBtn').click();
  await page.locator('#drawerDiscountMode').selectOption('exact');
  await page.locator('#drawerDiscountSlider').fill('10');
  await page.evaluate(()=>applyCustomDrawerFilters());
  await expect(page.locator('#gamesGrid h3')).toHaveText('Descuento 10');
  await page.locator('#drawerDiscountMode').selectOption('range');
  await page.locator('#drawerDiscountEnd').fill('30');
  await page.evaluate(()=>applyCustomDrawerFilters());
  await expect(page.locator('#gamesGrid .steam-card')).toHaveCount(3);
  await expect(page.locator('#gamesGrid')).not.toContainText('Descuento 31');
  await page.locator('[data-chip="all"]').click();
  await expect(page.locator('#gamesGrid .steam-card')).toHaveCount(3);
  await expect(page.locator('#catalogScopeNote')).toContainText('incluye juegos con y sin descuento');
  await page.locator('#drawerDiscountMode').selectOption('exact');
  await page.locator('#drawerDiscountSlider').fill('0');
  await page.evaluate(()=>applyCustomDrawerFilters());
  await expect(page.locator('#gamesGrid h3')).toHaveText('Descuento 0');
  await page.locator('#drawerRatingSlider').fill('80');
  await page.evaluate(()=>applyCustomDrawerFilters());
  await page.locator('#predictiveSearchInput').fill('mario');
  await page.locator('#predictiveSearchInput').press('Enter');
  await expect(page.locator('#gamesGrid h3')).toHaveText('Descuento 0');
  await expect.poll(()=>catalogQueries.at(-1)?.get('title')).toBe('mario');
  assert.equal(catalogQueries.at(-1).get('steamRating'),'80');
  await page.locator('[data-ecosystem="xbox"]').click();
  await expect(page.locator('.console-card')).toHaveCount(6);
  await page.locator('#consoleDiscountMode').selectOption('exact');
  await expect(page.locator('.console-card h3')).toHaveText('Descuento 10');
  await page.locator('#consoleDiscountMode').selectOption('range');
  await page.locator('#consoleDiscountEnd').fill('30');
  await page.locator('#consoleDiscountEnd').press('Tab');
  await expect(page.locator('.console-card')).toHaveCount(3);
  await page.locator('[data-chip="all"]').click();
  await expect(page.locator('.console-card')).toHaveCount(3);
  await page.evaluate(()=>resetConsoleFilters());
  await expect(page.locator('.console-card')).toHaveCount(7);
  await page.setViewportSize({width:390,height:844});
  await page.locator('#mobileFilterPanel>summary').click();
  await expect(page.locator('#consoleDiscountMode')).toBeVisible();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'test-results/refined-console-filters-mobile.png'});
  assert.deepEqual(errors,[]);
 }finally{await browser.close();await new Promise(r=>server.close(r));}
});
